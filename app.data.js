function computeResult(answers, meta) {
  const warnings = [];
  // 效度预警
  if ((answers[57] || 0) >= 4) warnings.push("Q57 社会期许");
  if ((answers[60] || 0) >= 4) warnings.push("Q60 作答态度");
  if (answers[58] && answers[22] && Math.abs(answers[58] - answers[22]) >= 2) warnings.push("Q58 一致性");
  if (answers[59] && answers[19] && Math.abs(answers[59] - answers[19]) >= 2) warnings.push("Q59 一致性");
  if (meta && meta.durationSec != null && meta.durationSec < 120) warnings.push("作答过快");
  if (meta && meta.maxSameStreak != null && meta.maxSameStreak >= 10) warnings.push("连续同选项");

  const domainScores = {};
  Object.keys(DOMAINS).forEach(k => {
    const items = QUESTIONS.filter(q => q.d === k);
    let sum = 0;
    items.forEach(q => {
      const raw = Number(answers[q.id]);
      const safe = Number.isFinite(raw) ? Math.min(5, Math.max(1, raw)) : 3; // 非法值按中性 3 分处理
      sum += q.r ? (6 - safe) : safe;
    });
    domainScores[k] = sum / items.length; // 1-5 均分
  });

  const sorted = Object.keys(domainScores).sort((a, b) => domainScores[b] - domainScores[a]);
  const top5 = sorted.slice(0, 5);
  const dualCore = (domainScores[sorted[0]] - domainScores[sorted[1]]) < 0.1;

  return { domainScores, sorted, top5, dualCore, warnings, invalid: warnings.length >= 3 };
}
